package com.safepath;

import android.app.Application;

import com.facebook.react.PackageList;
import com.facebook.react.ReactApplication;
import com.facebook.react.ReactNativeHost;
import com.facebook.react.ReactPackage;
import com.facebook.react.shell.MainReactPackage;
import com.facebook.soloader.SoLoader;
import com.safepath.location.LocationPackage;
import com.safepath.sms.DirectSmsPackage;

import java.util.ArrayList;
import java.util.List;

/**
 * Main application class for SafePath (Marg Rakshak).
 * Registers React Native core host, autolinked packages, and custom native modules.
 */
public class MainApplication extends Application implements ReactApplication {

    private final ReactNativeHost mReactNativeHost =
            new ReactNativeHost(this) {
                @Override
                public boolean getUseDeveloperSupport() {
                    return false; // The distributed APK loads its embedded JavaScript bundle.
                }

                @Override
                protected List<ReactPackage> getPackages() {
                    List<ReactPackage> packages;
                    try {
                        // PackageList is generated by React Native CLI autolinking
                        packages = new PackageList(this).getPackages();
                    } catch (Exception | NoClassDefFoundError e) {
                        // Safe fallback if PackageList has not yet been generated
                        packages = new ArrayList<>();
                        packages.add(new MainReactPackage());
                    }

                    // Register custom Android native modules
                    packages.add(new LocationPackage());
                    packages.add(new DirectSmsPackage());

                    return packages;
                }

                @Override
                protected String getJSMainModuleName() {
                    return "index";
                }
            };

    @Override
    public ReactNativeHost getReactNativeHost() {
        return mReactNativeHost;
    }

    @Override
    public void onCreate() {
        super.onCreate();
        try {
            SoLoader.init(this, com.facebook.react.soloader.OpenSourceMergedSoMapping.INSTANCE);
        } catch (java.io.IOException e) {
            throw new IllegalStateException("Unable to initialize React Native libraries", e);
        }
    }
}
